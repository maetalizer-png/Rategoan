const BYTES = Uint8Array.from([
  0x00, 0x61, 0x73, 0x6d, 0x01, 0x00, 0x00, 0x00,
  0x01, 0x05, 0x01, 0x60, 0x00, 0x01, 0x7f,
  0x03, 0x02, 0x01, 0x00,
  0x07, 0x08, 0x01, 0x04, 0x73, 0x75, 0x6d, 0x34, 0x00, 0x00,
  0x0a, 0x19, 0x01, 0x17, 0x00,
  0xfd, 0x0c,
  0x01, 0x00, 0x00, 0x00,
  0x02, 0x00, 0x00, 0x00,
  0x03, 0x00, 0x00, 0x00,
  0x04, 0x00, 0x00, 0x00,
  0xfd, 0x1b, 0x00,
  0x0b,
]);

const wasm = globalThis.WebAssembly;
let instance = null;

export function simdReady() {
  return !!(wasm && wasm.validate(BYTES));
}

export function simdSum4() {
  if (!instance) {
    if (!simdReady()) return null;
    instance = new wasm.Instance(new wasm.Module(BYTES));
  }
  return instance.exports.sum4();
}
