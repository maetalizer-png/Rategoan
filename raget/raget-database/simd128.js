let topBox = null;
let topMem = null;

function topMachine() {
  if (!topBox) {
    if (!wasm || !wasm.validate(TOP_BYTES)) return null;
    topBox = new wasm.Instance(new wasm.Module(TOP_BYTES));
    topMem = topBox.exports.memory;
  }
  return topBox;
}

export function searchInt8Rows(matrix, count, dim, query) {
  if (!matrix || !query || count <= 0 || dim <= 0 || (dim % 16) !== 0) return null;
  const box = topMachine();
  if (!box) return null;
  const qBytes = dim;
  const need = qBytes + count * dim;
  const page = 65536;
  const pages = Math.ceil(need / page);
  const have = topMem.buffer.byteLength / page;
  if (have < pages) topMem.grow(pages - have);
  const view = new Uint8Array(topMem.buffer);
  view.set(query.subarray(0, dim), 0);
  view.set(matrix.subarray(0, count * dim), qBytes);
  const id = box.exports.top1(count, dim, 0, qBytes);
  return { id, score: box.exports.score.value };
}
