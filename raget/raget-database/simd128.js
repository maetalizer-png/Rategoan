const wasm = globalThis.WebAssembly;
let instance = null;

function machine() {
  if (!instance) {
    if (!wasm || !wasm.validate(BYTES)) return null;
    instance = new wasm.Instance(new wasm.Module(BYTES));
  }
  return instance;
}

export function simdReady() {
  return !!(wasm && wasm.validate(BYTES));
}

export function dotI32x4(left, right) {
  const box = machine();
  if (!box) return null;
  const view = new DataView(box.exports.m.buffer);
  for (let i = 0; i < 4; i += 1) {
    view.setInt32(i * 4, left[i] | 0, true);
    view.setInt32(16 + i * 4, right[i] | 0, true);
  }
  return box.exports.lane();
}

export function dotInt8(left, right) {
  const n = Math.min(left.length, right.length);
  let acc = 0;
  let i = 0;
  for (; i + 16 <= n; i += 16) {
    acc += left[i] * right[i] + left[i + 1] * right[i + 1] + left[i + 2] * right[i + 2] + left[i + 3] * right[i + 3];
    acc += left[i + 4] * right[i + 4] + left[i + 5] * right[i + 5] + left[i + 6] * right[i + 6] + left[i + 7] * right[i + 7];
    acc += left[i + 8] * right[i + 8] + left[i + 9] * right[i + 9] + left[i + 10] * right[i + 10] + left[i + 11] * right[i + 11];
    acc += left[i + 12] * right[i + 12] + left[i + 13] * right[i + 13] + left[i + 14] * right[i + 14] + left[i + 15] * right[i + 15];
  }
  for (; i < n; i += 1) acc += left[i] * right[i];
  return acc;
}

