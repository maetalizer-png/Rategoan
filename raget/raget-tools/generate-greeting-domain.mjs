// ---------- builder ----------
let seq = 0;
function makeRecord(jenis, tags, teks, extraMeta) {
  seq += 1;
  const slug = String(teks)
    .toLowerCase()
    .replace(/[^a-z0-9\s-]/g, '')
    .trim()
    .split(/\s+/)
    .slice(0, 6)
    .join('-');
  return {
    id: 'greeting-' + jenis + '-' + seq + '-' + slug,
    kategori: 'sapaan',
    wilayah: null,
    nama: 'Greeting (' + jenis + '): ' + teks.slice(0, 40),
    tags: ['greeting', jenis, ...tags],
    teks,
    meta: { jenis, ...extraMeta },
  };
}

function buildAll() {
  const records = [];
  for (const teks of SAPA) records.push(makeRecord('sapa', [], teks, {}));
  for (const teks of SALAM) records.push(makeRecord('salam', [], teks, {}));
  for (const teks of BASA_BASI) records.push(makeRecord('basa-basi', [], teks, {}));
  for (const teks of TANYA_KABAR) records.push(makeRecord('tanya-kabar', [], teks, {}));
  for (const occasion of Object.keys(UCAPAN)) {
    for (const teks of UCAPAN[occasion]) records.push(makeRecord('ucapan', [occasion], teks, { occasion }));
  }
  return records;
}

function main() {
  const existing = JSON.parse(readFileSync(SAPAAN_FILE, 'utf8'));
  const existingCount = existing.length;
  const newRecords = buildAll();
  const merged = existing.concat(newRecords);
  writeFileSync(SAPAAN_FILE, JSON.stringify(merged, null, 2) + '\n', 'utf8');

  const byJenis = newRecords.reduce((acc, r) => {
    acc[r.meta.jenis] = (acc[r.meta.jenis] || 0) + 1;
    return acc;
  }, {});

  const report = {
    generatedAt: new Date().toISOString(),
    seedFileBefore: existingCount,
    baruDitambahkan: newRecords.length,
    totalSetelah: merged.length,
    perKategori: byJenis,
    domain: 'greeting',
    catatan: 'Semua baris ditulis manual/kurasi langsung (bukan cartesian-product acak), disimpan sebagai domain sapaan/greeting di raget-data/json/sapaan/sapaan.json untuk dipakai dataries-ke-korpus.mjs sebagai bahan SFT.',
  };
  mkdirSync(path.dirname(REPORT_FILE), { recursive: true });
  writeFileSync(REPORT_FILE, JSON.stringify(report, null, 2) + '\n', 'utf8');

  console.log('=== generate-greeting-domain ===');
  console.log('sapaan.json sebelum:', existingCount, 'entri');
  console.log('Baru ditambahkan   :', newRecords.length, 'entri');
  console.log('Total sesudah      :', merged.length, 'entri');
  console.log('Per kategori       :', JSON.stringify(byJenis));
  console.log('Report ditulis ke  :', path.relative(ROOT, REPORT_FILE));
}

main();
